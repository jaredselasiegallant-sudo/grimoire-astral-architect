namespace Grimoire.Core.Enums;

/// <summary>Expedition types that familiars can specialize in.</summary>
public enum ExpeditionType
{
    Gathering,    // Resource collection (best: Wisp, Sprite)
    Exploration,  // Map discovery, ruins (best: Drakling, Foxfire)
    Delving,      // Deep Void mining (best: Golem, Shade)
    Soothing,     // Calming Void corruption (best: Mothwing, Sprite)
    Arcane        // Spell component collection (best: Wisp, Foxfire)
}
